"""Generate the inline Lucide icon map used by the {% icon %} template tag.

Run once during scaffolding; the generated module is committed. No runtime dependency.
"""

from __future__ import annotations

import re
import urllib.request
from pathlib import Path

ICON_NAMES = [
    "archive",
    "archive-restore",
    "arrow-left",
    "arrow-up-down",
    "calendar-check",
    "chart-line",
    "check",
    "chevron-down",
    "chevron-right",
    "chevron-up",
    "clipboard-list",
    "copy",
    "dumbbell",
    "ellipsis-vertical",
    "grip-vertical",
    "history",
    "library",
    "log-out",
    "pencil",
    "play",
    "plus",
    "search",
    "settings",
    "skip-forward",
    "timer",
    "trash-2",
    "trending-up",
    "triangle-alert",
    "trophy",
    "x",
]

BASE = "https://unpkg.com/lucide-static@latest/icons/{name}.svg"
OUT = Path(r"C:\Users\Owner\src\liftlist\apps\core\templatetags\_icon_data.py")

HEADER = '''"""Lucide icon paths (ISC licensed, https://lucide.dev).

Generated by bin/generate_icons.py. Do not edit by hand.
"""

ICONS = {
'''

pattern = re.compile(r"<svg[^>]*>(.*?)</svg>", re.DOTALL)

lines = [HEADER]
for name in ICON_NAMES:
    with urllib.request.urlopen(BASE.format(name=name), timeout=30) as response:
        svg = response.read().decode("utf-8")
    match = pattern.search(svg)
    if not match:
        raise SystemExit(f"Could not parse {name}")
    inner = " ".join(match.group(1).split())
    if '"' in inner:
        literal = "'" + inner.replace("\\", "\\\\").replace("'", "\\'") + "'"
    else:
        literal = '"' + inner + '"'
    one_line = f'    "{name}": ({literal}),\n'
    if len(one_line.rstrip("\n")) <= 100:
        lines.append(one_line)
    else:
        lines.append(f'    "{name}": (\n        {literal}\n    ),\n')
lines.append("}\n")

OUT.write_text("".join(lines), encoding="utf-8")
print(f"Wrote {len(ICON_NAMES)} icons to {OUT}")
